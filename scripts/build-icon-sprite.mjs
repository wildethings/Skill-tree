// Builds a single local SVG sprite sheet + a search catalog from @phosphor-icons/core.
// Run via `npm run icons` (wired into dev and build). Nothing is fetched at runtime.
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { icons } from '@phosphor-icons/core'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const WEIGHT = 'duotone'
const assets = resolve(root, 'node_modules/@phosphor-icons/core/assets', WEIGHT)
const SPRITE_OUT = resolve(root, 'public/icons/ph-duotone.svg')
const CATALOG_OUT = resolve(root, 'src/lib/icons/catalog.generated.ts')

// Pull the drawable children out of a Phosphor source file. Every asset is a
// single <svg viewBox="0 0 256 256"> wrapper around one or two <path>s.
const innerOf = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim()

const symbols = []
const catalog = []

for (const icon of icons) {
  const file = resolve(assets, `${icon.name}-${WEIGHT}.svg`)
  if (!existsSync(file)) continue
  const inner = innerOf(await readFile(file, 'utf8'))
  if (!inner) continue
  symbols.push(`<symbol id="ph-${icon.name}" viewBox="0 0 256 256">${inner}</symbol>`)
  // `terms` is the pre-lowercased haystack the picker's index tokenises.
  catalog.push({
    name: icon.name,
    terms: [icon.name.replace(/-/g, ' '), ...icon.categories, ...icon.tags.filter((t) => !t.startsWith('*'))]
      .join(' ')
      .toLowerCase(),
  })
}

await mkdir(dirname(SPRITE_OUT), { recursive: true })
await writeFile(
  SPRITE_OUT,
  `<svg xmlns="http://www.w3.org/2000/svg" fill="currentColor" style="display:none">${symbols.join('')}</svg>`,
)

await mkdir(dirname(CATALOG_OUT), { recursive: true })
await writeFile(
  CATALOG_OUT,
  `// Generated by scripts/build-icon-sprite.mjs — do not edit.\n` +
    `export type IconMeta = { name: string; terms: string }\n` +
    `export const ICON_CATALOG: IconMeta[] = ${JSON.stringify(catalog)}\n`,
)

console.log(`icons: ${symbols.length} symbols -> public/icons/ph-duotone.svg`)
